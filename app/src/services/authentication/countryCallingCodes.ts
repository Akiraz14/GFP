export type CountryCallingCode = {
  regionCode: string;
  name: string;
  callingCode: string;
};

export const DEFAULT_PHONE_REGION = 'CO';

const REGIONAL_INDICATOR_A = 0x1f1e6;
const REGION_CODE = /^[A-Z]{2}$/;

export function flagEmoji(regionCode: string): string {
  if (!REGION_CODE.test(regionCode)) {
    return '';
  }
  return String.fromCodePoint(
    ...Array.from(
      regionCode,
      letter => REGIONAL_INDICATOR_A + letter.charCodeAt(0) - 65,
    ),
  );
}

export function countryLabel(country: CountryCallingCode): string {
  return `${flagEmoji(country.regionCode)} ${country.name} (${
    country.callingCode
  })`;
}

